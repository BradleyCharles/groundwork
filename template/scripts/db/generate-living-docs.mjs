#!/usr/bin/env node
// Generates supabase/schema.sql and supabase/policies.sql from the Postgres catalog.
// Default source: the local Supabase database. `--remote` reads DB_URL from the gitignored
// .env.db.local instead. The connection string is never printed.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import pg from "pg";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const LOCAL_URL = "postgresql://postgres:postgres@127.0.0.1:54322/postgres";
const SCHEMA = "public";
const OWNERS = ["postgres", "supabase_admin"];
const HEADER = (name) =>
  `-- ${name}: GENERATED by scripts/db/generate-living-docs.mjs. Do not edit by hand.\n-- Change a migration in supabase/migrations/, then run \`npx supabase db reset\` and regenerate.\n`;

export function resolveConnectionString(argv, cwd = ROOT) {
  if (!argv.includes("--remote")) return LOCAL_URL;
  const file = join(cwd, ".env.db.local");
  if (!existsSync(file)) throw new Error("--remote needs DB_URL in .env.db.local (gitignored)");
  const line = readFileSync(file, "utf8")
    .split(/\r?\n/)
    .find((l) => l.startsWith("DB_URL="));
  if (!line) throw new Error(".env.db.local has no DB_URL entry");
  return line.slice("DB_URL=".length).trim();
}

const q = (ident) => `"${ident.replaceAll('"', '""')}"`;
const qual = (name) => `${q(SCHEMA)}.${q(name)}`;

export function renderGrantLines(rows, kind) {
  // rows: { object, grantee, privileges[] , columns? }
  return rows
    .map((r) => {
      const to = r.grantee === "PUBLIC" ? "PUBLIC" : q(r.grantee);
      const privs = r.privileges.join(", ");
      if (kind === "column") return `grant ${privs} (${r.column}) on table ${r.object} to ${to};`;
      if (kind === "function") return `grant execute on function ${r.object} to ${to};`;
      return `grant ${privs} on table ${r.object} to ${to};`;
    })
    .sort();
}

async function rows(client, sql, params = []) {
  return (await client.query(sql, params)).rows;
}

export async function generate(client) {
  // Empty search_path makes catalog helpers (regclass, pg_get_*def) emit fully qualified names.
  await client.query("set search_path = ''");
  const tables = await rows(
    client,
    `select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
     from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = $1 and c.relkind in ('r','p') order by c.relname`,
    [SCHEMA],
  );

  const out = [HEADER("schema.sql")];

  const functions = await rows(
    client,
    `select p.oid, pg_get_functiondef(p.oid) as def, p.oid::regprocedure::text as sig
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = $1 and p.prokind in ('f','p')
       and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
     order by p.oid::regprocedure::text`,
    [SCHEMA],
  );
  out.push("-- Functions");
  for (const f of functions) out.push(f.def.trim() + ";\n");

  out.push("-- Tables");
  for (const t of tables) {
    const cols = await rows(
      client,
      `select a.attname, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull,
              a.attidentity, a.attgenerated, pg_get_expr(d.adbin, d.adrelid) as default_expr
       from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
       where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped order by a.attnum`,
      [t.oid],
    );
    const lines = cols.map((c) => {
      let l = `  ${q(c.attname)} ${c.type}`;
      if (c.attidentity === "a") l += " generated always as identity";
      else if (c.attidentity === "d") l += " generated by default as identity";
      else if (c.attgenerated === "s") l += ` generated always as (${c.default_expr}) stored`;
      else if (c.default_expr) l += ` default ${c.default_expr}`;
      if (c.attnotnull) l += " not null";
      return l;
    });
    out.push(`create table ${qual(t.relname)} (\n${lines.join(",\n")}\n);\n`);
  }

  const constraints = await rows(
    client,
    `select c.conrelid::regclass::text as tbl, c.conname, pg_get_constraintdef(c.oid) as def, c.contype
     from pg_constraint c join pg_namespace n on n.oid = c.connamespace
     where n.nspname = $1 and c.contype in ('p','u','c','f','x')
     order by array_position(array['p','u','c','x','f']::"char"[], c.contype), c.conrelid::regclass::text, c.conname`,
    [SCHEMA],
  );
  out.push("-- Constraints");
  for (const c of constraints) {
    out.push(`alter table only ${c.tbl} add constraint ${q(c.conname)} ${c.def};`);
  }

  const indexes = await rows(
    client,
    `select pg_get_indexdef(i.indexrelid) as def
     from pg_index i join pg_class c on c.oid = i.indexrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = $1 and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
     order by c.relname`,
    [SCHEMA],
  );
  out.push("\n-- Indexes");
  for (const i of indexes) out.push(i.def + ";");

  const triggers = await rows(
    client,
    `select pg_get_triggerdef(t.oid) as def, c.relnamespace::regnamespace::text as tbl_schema, t.tgname
     from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_proc p on p.oid = t.tgfoid
     where not t.tgisinternal and (c.relnamespace = $1::regnamespace or p.pronamespace = $1::regnamespace)
     order by c.relnamespace::regnamespace::text, c.relname, t.tgname`,
    [SCHEMA],
  );
  out.push("\n-- Triggers");
  for (const t of triggers) out.push(t.def + ";");

  const eventTriggers = await rows(
    client,
    `select e.evtname, e.evtevent, e.evttags, e.evtfoid::regproc::text as fn
     from pg_event_trigger e
     where e.evtfoid::regproc::text like $1 order by e.evtname`,
    [`${SCHEMA}.%`],
  );
  out.push("\n-- Event triggers");
  for (const e of eventTriggers) {
    const when = e.evttags ? `\n  when tag in (${e.evttags.map((x) => `'${x}'`).join(", ")})` : "";
    out.push(
      `create event trigger ${q(e.evtname)} on ${e.evtevent}${when}\n  execute function ${e.fn}();`,
    );
  }

  // ---- policies.sql ----
  const pol = [HEADER("policies.sql")];
  pol.push("-- Row level security");
  for (const t of tables) {
    pol.push(
      `alter table ${qual(t.relname)} enable row level security;`.replace(
        /^/,
        t.relrowsecurity ? "" : "-- NOT ENABLED: ",
      ),
    );
    if (t.relforcerowsecurity) pol.push(`alter table ${qual(t.relname)} force row level security;`);
  }

  const policies = await rows(
    client,
    `select tablename, policyname, permissive, roles::text[] as roles, cmd, qual, with_check
     from pg_policies where schemaname = $1 order by tablename, policyname`,
    [SCHEMA],
  );
  pol.push("\n-- Policies");
  for (const p of policies) {
    let s = `create policy ${q(p.policyname)} on ${qual(p.tablename)}\n  as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${p.roles.join(", ")}`;
    if (p.qual) s += `\n  using (${p.qual})`;
    if (p.with_check) s += `\n  with check (${p.with_check})`;
    pol.push(s + ";");
  }

  const tableGrants = await rows(
    client,
    `select c.oid::regclass::text as object, coalesce(r.rolname, 'PUBLIC') as grantee,
            array_agg(a.privilege_type order by a.privilege_type) as privileges
     from pg_class c join pg_namespace n on n.oid = c.relnamespace,
          lateral aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) a
          left join pg_roles r on r.oid = a.grantee
     where n.nspname = $1 and c.relkind in ('r','p') and a.grantee <> c.relowner
       and coalesce(r.rolname, 'PUBLIC') <> all($2)
     group by 1, 2`,
    [SCHEMA, OWNERS],
  );
  const columnGrants = await rows(
    client,
    `select c.oid::regclass::text as object, a.attname as "column", coalesce(r.rolname, 'PUBLIC') as grantee,
            array_agg(x.privilege_type order by x.privilege_type) as privileges
     from pg_class c join pg_namespace n on n.oid = c.relnamespace
       join pg_attribute a on a.attrelid = c.oid and a.attacl is not null and not a.attisdropped,
          lateral aclexplode(a.attacl) x left join pg_roles r on r.oid = x.grantee
     where n.nspname = $1 and c.relkind in ('r','p') and coalesce(r.rolname, 'PUBLIC') <> all($2)
     group by 1, 2, 3`,
    [SCHEMA, OWNERS],
  );
  const fnGrants = await rows(
    client,
    `select p.oid::regprocedure::text as object, coalesce(r.rolname, 'PUBLIC') as grantee,
            array['EXECUTE'] as privileges
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace,
          lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
          left join pg_roles r on r.oid = a.grantee
     where n.nspname = $1 and a.grantee <> p.proowner and coalesce(r.rolname, 'PUBLIC') <> all($2)
       and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')`,
    [SCHEMA, OWNERS],
  );
  pol.push("\n-- Table grants");
  pol.push(...renderGrantLines(tableGrants, "table"));
  pol.push("\n-- Column grants");
  pol.push(...renderGrantLines(columnGrants, "column"));
  pol.push("\n-- Function grants");
  pol.push(...renderGrantLines(fnGrants, "function"));

  return {
    schema:
      out
        .join("\n")
        .replace(/\n{3,}/g, "\n\n")
        .trimEnd() + "\n",
    policies:
      pol
        .join("\n")
        .replace(/\n{3,}/g, "\n\n")
        .trimEnd() + "\n",
  };
}

async function main() {
  const client = new pg.Client({
    connectionString: resolveConnectionString(process.argv.slice(2)),
  });
  try {
    await client.connect();
  } catch (e) {
    console.error(
      `Could not connect to the database (${e.code ?? "error"}). Is \`npx supabase start\` running?`,
    );
    process.exit(1);
  }
  try {
    const { schema, policies } = await generate(client);
    writeFileSync(join(ROOT, "supabase", "schema.sql"), schema);
    writeFileSync(join(ROOT, "supabase", "policies.sql"), policies);
    console.log("Wrote supabase/schema.sql and supabase/policies.sql");
  } finally {
    await client.end();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
