export const MODULE_IDS = ["ai", "crypto", "email", "supabase-mcp", "rolecheck"] as const;
export type ModuleId = (typeof MODULE_IDS)[number];

/** Only npm is supported in v0.1: the permission rules, CI and lockfile are npm-specific (see ADR 0014). */
export const PACKAGE_MANAGERS = ["npm"] as const;
export type PackageManager = (typeof PACKAGE_MANAGERS)[number];

export const MODULE_INFO: Record<ModuleId, { title: string; hint: string }> = {
  ai: {
    title: "AI integration",
    hint: "model config, request allowlist, timeout and error mapping",
  },
  crypto: {
    title: "Encryption at rest",
    hint: "AES-256-GCM helper with versioned ciphertext",
  },
  email: {
    title: "Email (Resend)",
    hint: "email client with timeouts and HTML-escaped templates",
  },
  "supabase-mcp": {
    title: "Supabase MCP",
    hint: ".mcp.json with read_only=true",
  },
  rolecheck: { title: "rolecheck spec", hint: "rolecheck.yaml stub" },
};

export interface Answers {
  projectName: string;
  packageName: string;
  description: string;
  scope: string;
  roles: string[];
  modules: ModuleId[];
  packageManager: PackageManager;
  supabaseProjectRef: string;
}

export const DEFAULT_DESCRIPTION = "Starter application generated by groundwork.";
export const DEFAULT_SCOPE =
  "Starter Next.js and Supabase application with a security baseline, WCAG 2.2 AA accessibility, and living documentation. Replace this paragraph with the project's scope statement.";
export const DEFAULT_PROJECT_REF = "YOUR_PROJECT_REF";

// These values are written into TypeScript string literals, JSX text, JSON, TOML and Markdown, so the
// allowed characters exclude quotes, backslashes, backticks, braces, angle brackets and `$`.
const PROJECT_NAME = /^[\p{L}\p{N}][\p{L}\p{N} .,&'():-]{0,59}$/u;
const DESCRIPTION = /^[\p{L}\p{N}][\p{L}\p{N} .,;:!?&'()/+@#_-]{0,199}$/u;
const PACKAGE_NAME = /^[a-z][a-z0-9-]{0,49}$/;
const ROLE = /^[a-z][a-z0-9_-]{0,31}$/;
const PROJECT_REF = /^(?:[a-z0-9]{1,40}|YOUR_PROJECT_REF)$/;

export const validators = {
  projectName: (v: string) =>
    PROJECT_NAME.test(v) ? null : "Use 1-60 letters, numbers, spaces or . , & ' ( ) : -",
  packageName: (v: string) =>
    PACKAGE_NAME.test(v)
      ? null
      : "Use lowercase letters, numbers and hyphens, starting with a letter (max 50)",
  description: (v: string) =>
    DESCRIPTION.test(v)
      ? null
      : "Use 1-200 characters; no quotes, backslashes, backticks, braces or angle brackets",
  scope: (v: string) => {
    if (
      v.length < 1 ||
      v.length > 600 ||
      /[\r\n\0]/.test(v) ||
      v.includes("{{") ||
      v.includes("}}")
    ) {
      return "Use one line of 1-600 characters without {{ or }}";
    }
    // AGENTS.md may not contain dates or plan numbers (the generated project's own lint fails on them).
    if (/\b\d{4}-\d{2}-\d{2}\b/.test(v))
      return "Leave dates out: AGENTS.md states current rules only (history goes in docs/decisions)";
    if (/\b(?:phase|week|milestone|roadmap item|roadmap #)\s*#?\d+/i.test(v))
      return "Leave plan or roadmap numbers out: AGENTS.md states current rules only";
    return null;
  },
  role: (v: string) =>
    ROLE.test(v)
      ? null
      : `Role "${v}" must be lowercase letters, numbers, _ or -, starting with a letter`,
  supabaseProjectRef: (v: string) =>
    PROJECT_REF.test(v) ? null : "Use the lowercase project ref from the Supabase dashboard",
};

export function packageNameFromDir(dir: string): string {
  const base = dir.split(/[\\/]/).filter(Boolean).pop() ?? "app";
  const cleaned = base
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return /^[a-z]/.test(cleaned)
    ? cleaned.slice(0, 50)
    : `app-${cleaned}`.slice(0, 50).replace(/-+$/g, "") || "app";
}

export function projectNameFromPackage(packageName: string): string {
  return packageName
    .split("-")
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join(" ");
}

export function defaultAnswers(dirName: string): Answers {
  const packageName = packageNameFromDir(dirName);
  return {
    projectName: projectNameFromPackage(packageName) || "My App",
    packageName,
    description: DEFAULT_DESCRIPTION,
    scope: DEFAULT_SCOPE,
    roles: [],
    modules: [],
    packageManager: "npm",
    supabaseProjectRef: DEFAULT_PROJECT_REF,
  };
}

/** Merges partial answers over defaults and validates the result. Returns every problem found. */
export function resolveAnswers(
  partial: Partial<Answers>,
  dirName: string,
): { answers: Answers; errors: string[] } {
  const base = defaultAnswers(dirName);
  // A package name given without a project name should still produce a sensible display name.
  if (partial.packageName && !partial.projectName)
    base.projectName = projectNameFromPackage(partial.packageName) || base.projectName;
  const answers: Answers = { ...base, ...stripUndefined(partial) };
  const errors: string[] = [];

  const check = (label: string, value: string, fn: (v: string) => string | null) => {
    const problem = fn(value);
    if (problem) errors.push(`${label}: ${problem}`);
  };
  check("projectName", answers.projectName, validators.projectName);
  check("packageName", answers.packageName, validators.packageName);
  check("description", answers.description, validators.description);
  check("scope", answers.scope, validators.scope);
  check("supabaseProjectRef", answers.supabaseProjectRef, validators.supabaseProjectRef);
  for (const role of answers.roles) check("roles", role, validators.role);
  if (new Set(answers.roles).size !== answers.roles.length) errors.push("roles: duplicate role");

  for (const m of answers.modules)
    if (!MODULE_IDS.includes(m))
      errors.push(`modules: unknown module "${m}" (known: ${MODULE_IDS.join(", ")})`);
  if (new Set(answers.modules).size !== answers.modules.length)
    errors.push("modules: duplicate module");
  if (!PACKAGE_MANAGERS.includes(answers.packageManager))
    errors.push(`packageManager: only ${PACKAGE_MANAGERS.join(", ")} is supported in this version`);

  // Canonical order keeps output deterministic however the modules were listed.
  answers.modules = MODULE_IDS.filter((m) => answers.modules.includes(m));
  return { answers, errors };
}

function stripUndefined<T extends object>(o: T): Partial<T> {
  return Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined)) as Partial<T>;
}

const NO_ROLES_LINE =
  "- Roles: stored in `app_metadata.role`, set only with the admin client. No role-restricted routes exist yet; use `requireRole([...])` when adding one.";

/** Values for {{TOKENS}} in template files. */
export function placeholderValues(a: Answers): Record<string, string> {
  const rolesLine =
    a.roles.length === 0
      ? NO_ROLES_LINE
      : `- Roles: ${a.roles.map((r) => `\`${r}\``).join(", ")} (stored in \`app_metadata.role\`, set only with the admin client). Use \`requireRole([...])\` to restrict a route to them.`;
  return {
    PROJECT_NAME: a.projectName,
    PACKAGE_NAME: a.packageName,
    PROJECT_DESCRIPTION: a.description,
    PROJECT_SCOPE_STATEMENT: a.scope,
    ROLES_LINE: rolesLine,
    ROLES_YAML: a.roles.length
      ? `roles:\n${a.roles.map((r) => `  - ${r}`).join("\n")}`
      : "roles: []",
    SUPABASE_PROJECT_REF: a.supabaseProjectRef,
  };
}
